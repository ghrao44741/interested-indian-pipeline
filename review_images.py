"""
review_images.py — AI-powered image QA for The Interested Indian pipeline.

Reads image_prompts_one_line_per_prompt.md, loads each generated image from
{project}/images/, sends it to Claude with a style/content rubric, and writes
a review report to {project}/review_report.md.

Usage:
    python review_images.py --project ep01
    python review_images.py --project ep01 --shot 07        # single shot
    python review_images.py --project ep01 --fail-only      # issues only
    python review_images.py --project ep01 --model sonnet   # sonnet for the whole batch
    python review_images.py --project ep01 --no-recheck     # haiku only, skip sonnet recheck

Requirements:
    pip install anthropic
    ANTHROPIC_API_KEY set in environment (or .env file in this folder)

Cost estimate (Haiku): ~$0.01–0.02 per image → ~$1–2 for all 90 images
Cost estimate (Sonnet): ~$0.05–0.10 per image → ~$4–9 for all 90 images

Two-tier review (default): the bulk pass runs on --model (haiku by default), then any
shot that comes back WARN or FAIL is automatically re-reviewed with Sonnet — Haiku is
cheap but occasionally hallucinates a style/content verdict (confirmed on real shots),
so the pricier model only gets used on the small slice that actually needs a second
opinion instead of the whole batch. Pass --no-recheck to disable, or --model sonnet to
run Sonnet on everything from the start (recheck is skipped in that case, it'd be redundant).
"""

