# ═══════════════════════════════════════════════════════════════════════════════
# PARSE PROMPTS FILE
# ═══════════════════════════════════════════════════════════════════════════════

def parse_prompts(md_path: str) -> list[dict]:
    """
    Parse image_prompts_one_line_per_prompt.md into a list of shot dicts.
    Each dict has: shot, filename, narration, prompt, overlay, cue, type

    `type` is looked up via route_images.parse_shots(), which applies the same
    TYPE/MAP_ARGS/CHART_ARGS validation and CARTOON-downgrade fallback used at
    generation time — so the review judges each shot against the style it was
    ACTUALLY routed/generated as, not just a raw (possibly stale) TYPE field.

    `chart_args`/`map_args` are captured the same way — CHART/MAP shots are
    rendered by generate_chart.py/generate_india_map.py from ONLY these
    structured args, never from the free-text PROMPT/INTENDED VISUAL (which
    still describes a narrative concept — often including the channel mascot —
    that these shot types never actually render). Passing the real args lets
    the reviewer judge CHART/MAP content against what was actually asked to be
    drawn, instead of a mascot-inclusive description that will never match.
    """
    shot_meta = {
        s["shot_num"]: s for s in route_images.parse_shots(Path(md_path))
    }
    type_by_shot_num = {num: s["type"] for num, s in shot_meta.items()}
    args_by_shot_num = {
        num: (s.get("chart_args") or s.get("map_args") or "")
        for num, s in shot_meta.items()
    }

    shots = []
    with open(md_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line.startswith("**SHOT"):
                continue

            # SHOT number
            shot_m = re.search(r"\*\*SHOT (\d+)\*\*", line)
            if not shot_m:
                continue
            shot = f"SHOT {shot_m.group(1).zfill(2)}"

            # Filename inside backticks
            fname_m = re.search(r"`([^`]+\.png)`", line)
            filename = fname_m.group(1) if fname_m else ""

            # NARRATION (quoted)
            narr_m = re.search(r'NARRATION:\s*"([^"]+)"', line)
            narration = narr_m.group(1) if narr_m else ""

            # PROMPT (between PROMPT: and OVERLAY:)
            prompt_m = re.search(r"PROMPT:\s*(.+?)\s*OVERLAY:", line)
            prompt = prompt_m.group(1) if prompt_m else ""

            # OVERLAY (between OVERLAY: and CUE:)
            overlay_m = re.search(r"OVERLAY:\s*(.+?)\s*CUE:", line)
            overlay = overlay_m.group(1) if overlay_m else ""

            # CUE (rest of line after CUE:)
            cue_m = re.search(r"CUE:\s*(.+)$", line)
            cue = cue_m.group(1) if cue_m else ""

            shot_num = int(shot_m.group(1))
            shots.append({
                "shot":       shot,
                "filename":   filename,
                "narration":  narration,
                "prompt":     prompt,
                "overlay":    overlay,
                "cue":        cue,
                "type":       type_by_shot_num.get(shot_num, "CARTOON"),
                "gen_args":   args_by_shot_num.get(shot_num, ""),
            })

    return shots


