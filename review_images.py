# REVIEW ONE IMAGE
# ═══════════════════════════════════════════════════════════════════════════════

def review_image(client: anthropic.Anthropic, shot: dict,
                 image_path: str, model: str, title: str) -> dict:
    """Send one image to Claude and return the parsed review dict."""
    img_b64, media_type = load_image_b64(image_path)

    shot_type = shot.get("type", "CARTOON")
    style_guide = STYLE_GUIDES.get(shot_type, STYLE_GUIDES["CARTOON"])

    gen_args = shot.get("gen_args", "")
    gen_args_block = ""
    if shot_type in ("CHART", "MAP") and gen_args:
        label = "CHART_ARGS" if shot_type == "CHART" else "MAP_ARGS"
        gen_args_block = (
            f"GENERATION ARGS ({label}) — this is what actually generated the image, "
            f"NOT the free-text INTENDED VISUAL above: {gen_args}\n"
        )

    user_prompt = REVIEW_PROMPT.format(
        shot=shot["shot"],
        shot_type=shot_type,
        filename=shot["filename"],
        narration=shot["narration"],
        prompt=shot["prompt"],
        gen_args_block=gen_args_block,
        overlay=shot["overlay"],
        cue=shot["cue"],
        style_guide=style_guide,
        title=title,
    )

    # claude-sonnet-5 uses extended thinking by default, which eats into max_tokens
    # before any output text is generated — 768 was tuned for haiku (no thinking) and
    # left sonnet with too little headroom, in one confirmed case producing a response
    # with ONLY a thinking block and no text at all. Give sonnet calls more room.
    max_tokens = 4096 if model == MODELS["sonnet"] else 768

    response = client.messages.create(
        model=model,
        max_tokens=max_tokens,
        messages=[{
            "role": "user",
            "content": [
                {
                    "type": "image",
                    "source": {
                        "type": "base64",
                        "media_type": media_type,
                        "data": img_b64,
                    },
                },
                {"type": "text", "text": user_prompt},
            ],
        }],
    )

    # claude-sonnet-5 uses extended thinking by default, so content[0] may be a
    # ThinkingBlock rather than the text response — find the actual text block
    # instead of assuming it's first (haiku has no thinking block, so this is
    # a no-op there — content[0] is still the text block).
    text_block = next((b for b in response.content if b.type == "text"), None)
    if text_block is None:
        raise RuntimeError(f"No text block in response (blocks: {[b.type for b in response.content]})")
    raw = text_block.text.strip()

    # Strip markdown code fences if present
    raw = re.sub(r"^```(?:json)?\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)

    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        # Fallback — extract verdict manually
        verdict = "WARN"
        if '"FAIL"' in raw or "'FAIL'" in raw:
            verdict = "FAIL"
        elif '"PASS"' in raw or "'PASS'" in raw:
            verdict = "PASS"
        return {
            "verdict":      verdict,
            "style_ok":     None,
            "content_match": None,
            "overlay_ok":   None,
            "ratio_ok":     None,
            "no_artifacts": None,
            "no_typos":     None,
            "on_topic":     None,
            "no_watermark": None,
            "typos_found":  [],
            "notes": f"[JSON parse error — raw: {raw[:120]}]",
        }


# ═══════════════════════════════════════════════════════════════════════════════
# REPORT WRITER
# ═══════════════════════════════════════════════════════════════════════════════

VERDICT_ICON = {"PASS": "✓", "WARN": "⚠", "FAIL": "✗", "SKIP": "—", "ERROR": "💥"}


def bool_icon(v) -> str:
    if v is True:  return "✓"
    if v is False: return "✗"
    return "?"


def write_report(results: list[dict], output_path: str, model_key: str,
                 total_shots: int, fail_only: bool, recheck_count: int = 0):
    passes  = sum(1 for r in results if r["result"].get("verdict") == "PASS")
    warns   = sum(1 for r in results if r["result"].get("verdict") == "WARN")
    fails   = sum(1 for r in results if r["result"].get("verdict") == "FAIL")
    skips   = sum(1 for r in results if r["result"].get("verdict") == "SKIP")
    errors  = sum(1 for r in results if r["result"].get("verdict") == "ERROR")
    reviewed = len([r for r in results if r["result"].get("verdict") not in ("SKIP",)])

    model_line = f"**Model:** {MODELS.get(model_key, model_key)}"
    if recheck_count:
        model_line += f" (bulk pass) + {MODELS['sonnet']} recheck on {recheck_count} WARN/FAIL shot(s)"

    lines = [
        f"# Image Review Report — ep01",
        f"**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        model_line,
        f"**Images reviewed:** {reviewed} / {total_shots}  "
        f"({'skipped ' + str(skips) + ' missing' if skips else 'all present'})",
        "",
        "## Summary",
        f"✓ PASS : {passes}",
        f"⚠ WARN : {warns}",
        f"✗ FAIL : {fails}",
        f"— SKIP : {skips}  ← image not found in images/",
        f"💥 ERROR: {errors}",
        "",
        "---",
        "",
        "## Results",
        "",
        "| Shot | File | Verdict | Style | Content | Overlay | Ratio | Artifacts | Typos | On-topic | Watermark | Notes |",
        "|------|------|---------|-------|---------|---------|-------|-----------|-------|----------|-----------|-------|",
    ]

    for r in results:
        res  = r["result"]
        v    = res.get("verdict", "?")
        icon = VERDICT_ICON.get(v, v)
        if fail_only and v == "PASS":
            continue
        row = (
            f"| {r['shot']} "
            f"| `{r['filename']}` "
            f"| {icon} {v} "
            f"| {bool_icon(res.get('style_ok'))} "
            f"| {bool_icon(res.get('content_match'))} "
            f"| {bool_icon(res.get('overlay_ok'))} "
            f"| {bool_icon(res.get('ratio_ok'))} "
            f"| {bool_icon(res.get('no_artifacts'))} "
            f"| {bool_icon(res.get('no_typos'))} "
            f"| {bool_icon(res.get('on_topic'))} "
            f"| {bool_icon(res.get('no_watermark'))} "
            f"| {res.get('notes', '')} |"
        )
        lines.append(row)

    # Issues section
    issues = [r for r in results if r["result"].get("verdict") in ("WARN", "FAIL", "ERROR")]
    if issues:
        lines += ["", "---", "", "## Issues requiring attention", ""]
        for r in issues:
            res  = r["result"]
            v    = res.get("verdict", "?")
            icon = VERDICT_ICON.get(v, v)
            lines.append(f"### {icon} {r['shot']} · `{r['filename']}` · {v}")
            lines.append(f"**Notes:** {res.get('notes', '—')}")
            checks = []
            for key, label in [
                ("style_ok",      "Style"),
                ("content_match", "Content"),
                ("overlay_ok",    "Overlay"),
                ("ratio_ok",      "Ratio"),
                ("no_artifacts",  "No artifacts"),
                ("no_typos",      "No typos"),
                ("on_topic",      "On-topic"),
                ("no_watermark",  "No watermark"),
            ]:
                checks.append(f"{bool_icon(res.get(key))} {label}")
            lines.append("  " + "  ·  ".join(checks))
            typos = res.get("typos_found", [])
            if typos:
                lines.append(f"**Typos found:** {' | '.join(typos)}")
            lines.append("")

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


