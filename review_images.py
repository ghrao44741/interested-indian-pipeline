def main():
    parser = argparse.ArgumentParser(
        description="AI image review for The Interested Indian pipeline"
    )
    parser.add_argument("--project", required=True,
                        help="Project folder (e.g. ep01), relative or absolute")
    parser.add_argument("--shot", type=int, default=None,
                        help="Review a single shot number (e.g. --shot 7)")
    parser.add_argument("--fail-only", action="store_true",
                        help="Only show WARN/FAIL entries in the report table")
    parser.add_argument("--model", choices=["haiku", "sonnet"], default=DEFAULT_MODEL,
                        help=f"Claude model to use for the bulk pass (default: {DEFAULT_MODEL})")
    parser.add_argument("--no-recheck", action="store_true",
                        help="Skip the automatic Sonnet recheck of WARN/FAIL shots (haiku-only run)")
    args = parser.parse_args()

    # ── resolve paths ──────────────────────────────────────────────────────────
    script_dir  = Path(__file__).parent
    project_dir = (
        Path(args.project) if Path(args.project).is_absolute()
        else (script_dir / args.project).resolve()
    )
    if not project_dir.is_dir():
        print(f"❌ Project folder not found: {project_dir}")
        sys.exit(1)

    prompts_path = project_dir / PROMPTS_FILE
    if not prompts_path.exists():
        print(f"❌ Prompts file not found: {prompts_path}")
        print(f"   Expected: {PROMPTS_FILE} inside the project folder")
        sys.exit(1)

    images_dir   = project_dir / "images"
    report_path  = project_dir / "review_report.md"
    model_name   = MODELS[args.model]

    # Read the actual episode title from manifest.json so on-topic/typo checks
    # judge against THIS project, not a fixed placeholder topic. Previously
    # hardcoded to "Article 356" (this reviewer's original test episode),
    # which silently produced false on-topic FAILs for every other project.
    title = project_dir.name.replace("_", " ").title()
    manifest_path = project_dir / "manifest.json"
    if manifest_path.exists():
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
            title = manifest.get("title") or title
        except (json.JSONDecodeError, OSError):
            pass

    # ── load prompts ───────────────────────────────────────────────────────────
    shots = parse_prompts(str(prompts_path))
    if not shots:
        print("❌ No shots parsed from prompts file — check the format.")
        sys.exit(1)

    # Filter to single shot if requested
    if args.shot is not None:
        target = f"SHOT {str(args.shot).zfill(2)}"
        shots = [s for s in shots if s["shot"] == target]
        if not shots:
            print(f"❌ {target} not found in prompts file.")
            sys.exit(1)

    # ── init Anthropic client ──────────────────────────────────────────────────
    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        # Try .env in script folder
        env_file = script_dir / ".env"
        if env_file.exists():
            for line in env_file.read_text().splitlines():
                if line.startswith("ANTHROPIC_API_KEY="):
                    api_key = line.split("=", 1)[1].strip().strip('"').strip("'")
                    break
    if not api_key:
        print("❌ ANTHROPIC_API_KEY not set.")
        print("   Set it as an environment variable or add it to a .env file:")
        print("   ANTHROPIC_API_KEY=sk-ant-...")
        sys.exit(1)

    client = anthropic.Anthropic(api_key=api_key)

    # ── review loop ────────────────────────────────────────────────────────────
    print(f"\n{'═' * 55}")
    print(f"Image Review — {project_dir.name}")
    print(f"Title     : {title}")
    print(f"Model     : {model_name}")
    print(f"Shots     : {len(shots)}")
    print(f"Images dir: {images_dir}")
    print(f"{'═' * 55}\n")

    results = []

    for i, shot in enumerate(shots, 1):
        filename = shot["filename"]

        # Find image file (try exact name, then case-insensitive)
        image_path = images_dir / filename
        if not image_path.exists():
            # Try other extensions
            stem = Path(filename).stem
            found = None
            for ext in [".png", ".jpg", ".jpeg", ".webp"]:
                candidate = images_dir / f"{stem}{ext}"
                if candidate.exists():
                    found = candidate
                    break
            image_path = found

        if not image_path:
            print(f"[{i:02d}/{len(shots)}] {shot['shot']} · {filename}  — SKIP (not found)")
            results.append({
                "shot":     shot["shot"],
                "filename": filename,
                "result": {
                    "verdict":       "SKIP",
                    "style_ok":      None,
                    "content_match": None,
                    "overlay_ok":    None,
                    "ratio_ok":      None,
                    "no_artifacts":  None,
                    "no_typos":      None,
                    "on_topic":      None,
                    "no_watermark":  None,
                    "typos_found":   [],
                    "notes":         "Image file not found in images/",
                },
            })
            continue

        print(f"[{i:02d}/{len(shots)}] {shot['shot']} · {filename}", end="  ", flush=True)

        try:
            review = review_image(client, shot, str(image_path), model_name, title)
            verdict = review.get("verdict", "?")
            icon    = VERDICT_ICON.get(verdict, verdict)
            print(f"{icon} {verdict}  — {review.get('notes', '')}")
            results.append({
                "shot":     shot["shot"],
                "filename": filename,
                "result":   review,
            })
        except Exception as e:
            print(f"💥 ERROR — {e}")
            results.append({
                "shot":     shot["shot"],
                "filename": filename,
                "result": {
                    "verdict":       "ERROR",
                    "style_ok":      None,
                    "content_match": None,
                    "overlay_ok":    None,
                    "ratio_ok":      None,
                    "no_artifacts":  None,
                    "no_typos":      None,
                    "on_topic":      None,
                    "no_watermark":  None,
                    "typos_found":   [],
                    "notes":         str(e)[:120],
                },
            })

        if i < len(shots):
            time.sleep(DELAY_BETWEEN_CALLS)

    # ── sonnet recheck of WARN/FAIL shots ──────────────────────────────────────
    # Haiku is the cheap default but occasionally hallucinates a verdict (confirmed
    # on real shots — e.g. flagging a correct flat-cartoon image as "photorealistic").
    # Rather than paying Sonnet's higher per-image cost on the whole batch, only the
    # shots that already came back WARN/FAIL get a second opinion from Sonnet, which
    # becomes the final verdict for that shot. Skipped entirely if the bulk pass was
    # already Sonnet (redundant) or --no-recheck was passed.
    recheck_targets = [
        r for r in results if r["result"].get("verdict") in ("WARN", "FAIL")
    ]
    if args.model != "sonnet" and not args.no_recheck and recheck_targets:
        print(f"\n{'─' * 55}")
        print(f"Sonnet recheck — {len(recheck_targets)} WARN/FAIL shot(s)")
        print(f"{'─' * 55}\n")

        shots_by_key = {(s["shot"], s["filename"]): s for s in shots}
        sonnet_model_name = MODELS["sonnet"]

        for i, r in enumerate(recheck_targets, 1):
            shot = shots_by_key.get((r["shot"], r["filename"]))
            if shot is None:
                continue
            image_path = images_dir / r["filename"]
            if not image_path.exists():
                continue

            original_verdict = r["result"].get("verdict")
            print(f"[{i:02d}/{len(recheck_targets)}] {r['shot']} · {r['filename']}"
                  f"  (was {original_verdict})", end="  ", flush=True)
            try:
                recheck = review_image(client, shot, str(image_path), sonnet_model_name, title)
                verdict = recheck.get("verdict", "?")
                icon = VERDICT_ICON.get(verdict, verdict)
                print(f"→ {icon} {verdict}  — {recheck.get('notes', '')}")
                recheck["notes"] = (
                    f"[Sonnet recheck, Haiku said {original_verdict}] "
                    f"{recheck.get('notes', '')}"
                ).strip()
                r["result"] = recheck
            except Exception as e:
                print(f"💥 recheck ERROR — {e} (keeping original {original_verdict})")

            if i < len(recheck_targets):
                time.sleep(DELAY_BETWEEN_CALLS)

    # ── write report ───────────────────────────────────────────────────────────
    did_recheck = args.model != "sonnet" and not args.no_recheck and bool(recheck_targets)
    write_report(results, str(report_path), args.model,
                 total_shots=len(shots), fail_only=args.fail_only,
                 recheck_count=len(recheck_targets) if did_recheck else 0)

    passes = sum(1 for r in results if r["result"].get("verdict") == "PASS")
    warns  = sum(1 for r in results if r["result"].get("verdict") == "WARN")
    fails  = sum(1 for r in results if r["result"].get("verdict") == "FAIL")
    skips  = sum(1 for r in results if r["result"].get("verdict") == "SKIP")

    print(f"\n{'═' * 55}")
    print(f"Review complete")
    print(f"  ✓ PASS : {passes}")
    print(f"  ⚠ WARN : {warns}")
    print(f"  ✗ FAIL : {fails}")
    print(f"  — SKIP : {skips}")
    print(f"\nReport: {report_path}")
    print(f"{'═' * 55}\n")

    if warns + fails > 0:
        sys.exit(1)   # non-zero exit so CI pipelines can catch issues


if __name__ == "__main__":
    main()
